def _build_svg_string(name: str, color_hex: str = "#E2E8F0", stroke_width: float = 2.0) -> str:
    path_content = _LUCIDE_PATHS.get(name, _LUCIDE_PATHS["sparkles"])
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="{color_hex}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">
{path_content}
</svg>"""


@functools.lru_cache(maxsize=256)
def get_pixmap(name: str, size: int = 16, color_hex: str = "#CBD5E1") -> QPixmap:
    """Return a crisp anti-aliased QPixmap of the requested Lucide icon."""
    svg_str = _build_svg_string(name, color_hex=color_hex)
    svg_bytes = QByteArray(svg_str.encode("utf-8"))
    renderer = QSvgRenderer(svg_bytes)

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    renderer.render(painter)
    painter.end()

    return pixmap


@functools.lru_cache(maxsize=128)
def get_icon(
    name: str, size: int = 16, color_hex: str = "#CBD5E1", active_color_hex: str = "#3B82F6"
) -> QIcon:
    """Return a stateful QIcon with normal and active/selected states."""
    icon = QIcon()
    normal_pix = get_pixmap(name, size, color_hex)
    active_pix = get_pixmap(name, size, active_color_hex)
    icon.addPixmap(normal_pix, QIcon.Mode.Normal)
    icon.addPixmap(active_pix, QIcon.Mode.Active)
    icon.addPixmap(active_pix, QIcon.Mode.Selected)
    return icon
