"""
Bengali ASS Subtitle & Typography Styler (libass / HarfBuzz / Noto Sans Bengali).

Implements Section 4 (Gotchas 6 & 9) from BRAIN.md:
- Unicode NFC normalization preventing broken conjuncts (যুক্তবর্ণ)
- HarfBuzz-ready Advanced SubStation Alpha (.ass) format with high-legibility typographic hierarchy
- Multi-tier Bengali font fallbacks: Noto Sans Bengali -> Kalpurush -> SolaimanLipi -> Segoe UI
- Support for Target-Only and Bilingual Dual-Track typography
"""

from __future__ import annotations

import logging
import unicodedata
from enum import StrEnum
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

BENGALI_FONT_STACK = "Noto Sans Bengali, Kalpurush, SolaimanLipi, Segoe UI"


class BengaliSubtitleStyle(StrEnum):
    THEATRICAL_BOTTOM = "theatrical_bottom"
    BILINGUAL_STACKED = "bilingual_stacked"
    BROADCAST_SDH = "broadcast_sdh"


def normalize_bengali_unicode(text: str) -> str:
    """
    Normalize Bengali text into canonical Unicode NFC representation.
    Ensures that virama/hasanta conjuncts (যেমন: ক + ্ + ষ -> ক্ষ, ব + া -> বা)
    remain perfectly shaped without decomposition in libass/HarfBuzz.
    """
    if not text:
        return ""
    # 1. Unicode Normalization Form C (Canonical Decomposition followed by Canonical Composition)
    normalized = unicodedata.normalize("NFC", text.strip())

    # 2. Fix isolated Nukta / Hasanta sequence anomalies
    # nukta (09BC), virama (09CD)
    normalized = normalized.replace("\u09cd\u09bc", "\u09bc\u09cd")

    # 3. Collapse multiple whitespaces
    return " ".join(normalized.split())


def format_ass_timestamp(seconds: float) -> str:
    """Format seconds into ASS timecode: H:MM:SS.cc (centiseconds)."""
    hrs = int(seconds // 3600)
    mins = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    cs = round((seconds - int(seconds)) * 100)
    if cs >= 100:
        cs = 99
    return f"{hrs:d}:{mins:02d}:{secs:02d}.{cs:02d}"


class BengaliAssStyler:
    """
    Advanced SubStation Alpha (.ass) subtitle styler for Indic & Bengali typography.
    """

    @classmethod
    def generate_ass(
        cls,
        segments: list[dict[str, Any]],
        output_path: Path | str,
        *,
        style_preset: BengaliSubtitleStyle = BengaliSubtitleStyle.BILINGUAL_STACKED,
        target_font: str = "Noto Sans Bengali",
        source_font: str = "Segoe UI",
        play_res_x: int = 1920,
        play_res_y: int = 1080,
    ) -> Path:
        """
        Generate a fully styled, broadcast-ready .ass subtitle file from dialogue segments.
        """
        out_p = Path(output_path)
        out_p.parent.mkdir(parents=True, exist_ok=True)

        header = [
            "[Script Info]",
            "; Script generated by AI Movie Dubbing Studio — Bengali Typography Engine",
            "ScriptType: v4.00+",
            "WrapStyle: 0",
            "ScaledBorderAndShadow: yes",
            f"PlayResX: {play_res_x}",
            f"PlayResY: {play_res_y}",
            "",
            "[V4+ Styles]",
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
            # Bengali Main Dialogue: Large, clean white with crisp black outline and subtle drop shadow
            f"Style: Bengali_Main,{target_font},52,&H00FFFFFF,&H000000FF,&H00121212,&H80000000,1,0,0,0,100,100,0,0,1,2.8,1.6,2,60,60,45,1",
            # English / Source Secondary Dialogue: Slightly smaller, light silver
            f"Style: English_Source,{source_font},34,&H00E2E2E2,&H000000FF,&H00121212,&H80000000,0,0,0,0,100,100,0,0,1,2.0,1.2,2,60,60,110,1",
            # SDH Sound Effect descriptors
            f"Style: SDH_Descriptor,{source_font},30,&H00FFFF80,&H000000FF,&H00101010,&H80000000,0,1,0,0,100,100,0,0,1,2.0,1.0,8,60,60,35,1",
            "",
            "[Events]",
            "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        ]

        events: list[str] = []
        for seg in segments:
            st = float(seg.get("start", 0.0))
            en = float(seg.get("end", st + 1.0))
            if en <= st:
                continue

            st_ts = format_ass_timestamp(st)
            en_ts = format_ass_timestamp(en)

            raw_tgt = str(seg.get("tgt", "")).strip()
            raw_src = str(seg.get("text") or seg.get("src", "")).strip()

            norm_tgt = normalize_bengali_unicode(raw_tgt)

            if style_preset == BengaliSubtitleStyle.THEATRICAL_BOTTOM:
                # Target language only at bottom center
                if norm_tgt:
                    events.append(f"Dialogue: 0,{st_ts},{en_ts},Bengali_Main,,0,0,0,,{norm_tgt}")
            elif style_preset == BengaliSubtitleStyle.BILINGUAL_STACKED:
                # Top/Bottom or vertically stacked: English on line 1, Bengali on line 2
                if raw_src and norm_tgt:
                    # In ASS, \\N creates a clean styled line break
                    stacked_text = f"{norm_tgt}\\N{{\\rEnglish_Source}}{raw_src}"
                    events.append(f"Dialogue: 0,{st_ts},{en_ts},Bengali_Main,,0,0,0,,{stacked_text}")
                elif norm_tgt:
                    events.append(f"Dialogue: 0,{st_ts},{en_ts},Bengali_Main,,0,0,0,,{norm_tgt}")
                elif raw_src:
                    events.append(f"Dialogue: 0,{st_ts},{en_ts},English_Source,,0,0,0,,{raw_src}")
            elif style_preset == BengaliSubtitleStyle.BROADCAST_SDH:
                speaker = str(seg.get("speaker", "")).strip()
                spk_prefix = f"{{\\c&H80FFFF&}}{speaker}: {{\\rBengali_Main}}" if speaker else ""
                events.append(f"Dialogue: 0,{st_ts},{en_ts},Bengali_Main,,0,0,0,,{spk_prefix}{norm_tgt}")

        out_content = "\n".join(header + events) + "\n"
        out_p.write_text(out_content, encoding="utf-8-sig")
        logger.info("Generated %d ASS subtitle cues at %s", len(events), out_p)
        return out_p


